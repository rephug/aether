use super::TemplateContext;

/// `.github/workflows/aether-review.yml`: an advisory pull-request review built from a
/// structural index only (no SIRs, no model calls, no API keys), posted as one comment
/// that is updated in place. See `docs/CI_SETUP.md`.
#[derive(Debug, Clone, Copy, Default)]
pub struct GithubReviewWorkflowTemplate;

impl GithubReviewWorkflowTemplate {
    pub fn render(context: &TemplateContext) -> String {
        // A Python tuple for `str.endswith`; a single element renders as a plain string,
        // which `endswith` accepts too.
        let suffixes = context
            .source_suffixes
            .iter()
            .map(|suffix| format!("\"{suffix}\""))
            .collect::<Vec<_>>()
            .join(", ");
        r####"# Advisory AETHER review, generated by `aetherd init-agent --platform claude`.
# Setup, costs and options:
# https://github.com/rephug/aether/blob/main/docs/CI_SETUP.md
#
# Builds a structural AETHER index of the pull request (no SIRs, no model calls,
# no API keys) and posts one comment that is updated in place on every push.
# It is advisory: don't make it a required check.
name: AETHER review

on:
  pull_request:
  # Scheduled and manual runs only build aetherd and save it to the default
  # branch's cache, which every pull request can restore.
  schedule:
    - cron: "23 4 * * 1"
  workflow_dispatch:

permissions:
  contents: read
  pull-requests: write

# Runs for the same PR (or ref) queue instead of cancelling each other, so a first
# aetherd build always gets to finish and be saved.
concurrency:
  group: aether-review-${{ github.event.pull_request.number || github.ref }}
  cancel-in-progress: false

env:
  # Where aetherd is built from: a branch, a tag or a full commit SHA. Pin a SHA
  # for reproducible runs and fewer rebuilds.
  AETHER_GIT_URL: https://github.com/rephug/aether
  AETHER_REF: main

defaults:
  run:
    shell: bash

jobs:
  review:
    name: AETHER review (advisory)
    runs-on: ubuntu-24.04
    continue-on-error: true
    timeout-minutes: 120
    steps:
      - name: Checkout
        if: github.event_name == 'pull_request'
        uses: actions/checkout@v5
        with:
          fetch-depth: 0
          persist-credentials: false

      - name: Resolve the AETHER revision
        id: aether
        run: |
          if [[ "$AETHER_REF" =~ ^[0-9a-f]{40}$ ]]; then
            rev="$AETHER_REF"
          else
            rev=$(git ls-remote "$AETHER_GIT_URL" "refs/heads/$AETHER_REF" | cut -f 1)
            [ -n "$rev" ] || rev=$(git ls-remote "$AETHER_GIT_URL" "refs/tags/$AETHER_REF^{}" | cut -f 1)
            [ -n "$rev" ] || rev=$(git ls-remote "$AETHER_GIT_URL" "refs/tags/$AETHER_REF" | cut -f 1)
          fi
          if [ -z "$rev" ]; then
            echo "::error::AETHER_REF '$AETHER_REF' is not a branch, tag or commit of $AETHER_GIT_URL"
            exit 1
          fi
          echo "rev=$rev" >> "$GITHUB_OUTPUT"

      # Pull requests take any cached aetherd, even one built from an older
      # revision; scheduled and manual runs rebuild when the revision moved.
      - name: Restore aetherd
        id: restore
        uses: actions/cache/restore@v4
        with:
          path: ${{ runner.tool_cache }}/aether-ci
          key: aetherd-${{ runner.os }}-${{ steps.aether.outputs.rev }}
          restore-keys: aetherd-${{ runner.os }}-

      - name: Build aetherd
        id: build
        if: >-
          steps.restore.outputs.cache-hit != 'true'
          && (github.event_name != 'pull_request' || steps.restore.outputs.cache-matched-key == '')
        env:
          PROTOC: /usr/bin/protoc
          AETHER_REV: ${{ steps.aether.outputs.rev }}
          CARGO_PROFILE_RELEASE_STRIP: "true"
        run: |
          sudo apt-get update
          sudo apt-get install -y protobuf-compiler
          rustup toolchain install stable --profile minimal
          rm -rf "$RUNNER_TOOL_CACHE/aether-ci"
          cargo +stable install --locked --git "$AETHER_GIT_URL" --rev "$AETHER_REV" \
            --root "$RUNNER_TOOL_CACHE/aether-ci" aetherd

      # Saved right away, so a later failure or a cancelled run doesn't lose it.
      - name: Save aetherd
        if: steps.build.outcome == 'success'
        uses: actions/cache/save@v4
        with:
          path: ${{ runner.tool_cache }}/aether-ci
          key: aetherd-${{ runner.os }}-${{ steps.aether.outputs.rev }}

      - name: Analyze the pull request
        if: github.event_name == 'pull_request'
        env:
          BASE_SHA: ${{ github.event.pull_request.base.sha }}
          HEAD_SHA: ${{ github.event.pull_request.head.sha }}
          RUST_LOG: warn
        run: |
          export PATH="$RUNNER_TOOL_CACHE/aether-ci/bin:$PATH"
          aetherd --workspace . --index-once --inference-provider mock
          aetherd mine-coupling --workspace . > /dev/null \
            || echo "::warning::Coupling mining failed; the review continues without it."
          python3 - <<'PY'
          import html
          import json
          import os
          import re
          import subprocess

          MARKER = "<!-- aether-review -->"
          SOURCE_SUFFIXES = (@SOURCE_SUFFIXES@)
          MAX_FILES = 15
          HEALTH_LIMIT = 200
          notes = []


          def cell(value):
              # Table cells: a pipe would split the cell, even inside backticks.
              return str(value).replace("|", "\\|").replace("\n", " ")


          def aetherd_json(*args):
              # RUST_LOG=off keeps log lines out of stdout, which carries the JSON.
              proc = subprocess.run(
                  ["aetherd", *args],
                  capture_output=True,
                  text=True,
                  env={**os.environ, "RUST_LOG": "off"},
              )
              if proc.returncode != 0:
                  lines = proc.stderr.strip().splitlines()
                  notes.append(f"`aetherd {args[0]}` failed: {lines[-1] if lines else proc.returncode}")
                  return None
              start = proc.stdout.find("\n{")
              start = 0 if proc.stdout.startswith("{") else start + 1 if start >= 0 else -1
              try:
                  if start >= 0:
                      return json.JSONDecoder().raw_decode(proc.stdout[start:])[0]
              except json.JSONDecodeError:
                  pass
              notes.append(f"`aetherd {args[0]}` printed no JSON")
              return None


          def changed_files(*filters):
              diff = subprocess.run(
                  ["git", "diff", "-z", "--name-only", *filters, f"{base}...{head}"],
                  capture_output=True,
                  text=True,
                  check=True,
              )
              return [path for path in diff.stdout.split("\0") if path]


          base, head = os.environ["BASE_SHA"], os.environ["HEAD_SHA"]
          # Every path the PR touches, deletions and rename sources included, decides what
          # counts as "in this PR"; only added, modified and renamed source files are analyzed.
          touched_set = set(changed_files())
          changed = [path for path in changed_files("--diff-filter=AMR") if path.endswith(SOURCE_SUFFIXES)]
          changed_set = set(changed)
          analyzed = changed[:MAX_FILES]

          out = [MARKER, "## AETHER structural review (advisory)", "", f"Head commit `{head[:12]}`."]
          if not changed:
              out += ["", "No changed source files in this pull request."]
          else:
              out += [
                  "",
                  f"{len(changed)} changed source file(s)"
                  + (f"; the first {MAX_FILES} are analyzed." if len(changed) > MAX_FILES else "."),
              ]

              # Files that usually change together with the changed ones, but are not in this PR.
              missing = []
              unchecked = 0
              for path in analyzed:
                  radius = aetherd_json("blast-radius", "--workspace", ".", "--min-risk", "medium", path)
                  if radius is None:
                      unchecked += 1
                      continue
                  for entry in radius.get("coupled_files", []):
                      if entry.get("file") not in touched_set:
                          missing.append((path, entry))
              out += ["", "### Usually changed together, but not in this PR", ""]
              if missing:
                  out += ["| Changed file | Coupled file | Risk | Co-changes |", "| --- | --- | --- | --- |"]
                  for path, entry in missing[:20]:
                      out.append(
                          f"| `{cell(path)}` | `{cell(entry.get('file'))}` | {cell(entry.get('risk_level'))} "
                          f"| {entry.get('co_change_count')} of {entry.get('total_commits')} commits |"
                      )
              elif unchecked == len(analyzed):
                  out.append("Unavailable: `aetherd blast-radius` failed; see the notes below.")
              else:
                  out.append("No medium-or-higher coupling outside this PR.")
              if 0 < unchecked < len(analyzed):
                  out += ["", f"{unchecked} file(s) could not be checked; see the notes below."]

              # Structurally risky symbols that live in the changed files.
              health = aetherd_json("health", "--workspace", ".", "--limit", str(HEALTH_LIMIT))
              health_failed = health is None
              health = health or {}
              risky = {}
              for section in ("critical_symbols", "risk_hotspots", "bottlenecks"):
                  for entry in health.get(section, []):
                      if entry.get("file") in changed_set:
                          risky.setdefault(entry.get("symbol_id"), entry)
              cycles = [
                  cycle for cycle in health.get("cycles", [])
                  if any(symbol.get("file") in changed_set for symbol in cycle.get("symbols", []))
              ]
              out += ["", "### Risky symbols in changed files", ""]
              if risky:
                  out += ["| Symbol | File | Risk | Factors |", "| --- | --- | --- | --- |"]
                  for entry in list(risky.values())[:15]:
                      risk = entry.get("risk_score")
                      # CI never generates SIRs, so their absence is not news here.
                      factors = ", ".join(
                          factor for factor in entry.get("risk_factors", []) if "SIR" not in factor
                      ) or entry.get("note", "")
                      out.append(
                          f"| `{cell(entry.get('symbol_name'))}` | `{cell(entry.get('file'))}` "
                          f"| {'' if risk is None else f'{risk:.2f}'} | {cell(factors)} |"
                      )
                  out += [
                      "",
                      "Risk scores here include a fixed offset for having no SIRs and no access "
                      "history, which every symbol shares in CI; compare them with each other.",
                  ]
              elif health_failed:
                  out.append("Unavailable: `aetherd health` failed; see the notes below.")
              else:
                  out.append(
                      f"None of the changed files holds one of the workspace's {HEALTH_LIMIT} most "
                      "critical, central or risky symbols."
                  )
              if cycles:
                  out += ["", f"{len(cycles)} dependency cycle(s) pass through the changed files."]

              # Crate health, for Cargo workspaces (health-score needs [workspace].members).
              manifest = open("Cargo.toml").read() if os.path.exists("Cargo.toml") else ""
              if re.search(r"(?m)^\[workspace\]", manifest):
                  score = aetherd_json("health-score", "--workspace", ".", "--output", "json", "--no-history")
                  if score:
                      touched = set()
                      meta = subprocess.run(
                          ["cargo", "metadata", "--no-deps", "--format-version", "1"],
                          capture_output=True,
                          text=True,
                      )
                      if meta.returncode == 0:
                          root = os.getcwd()
                          packages = []
                          for package in json.loads(meta.stdout).get("packages", []):
                              crate_dir = os.path.relpath(os.path.dirname(package["manifest_path"]), root)
                              packages.append(("" if crate_dir == "." else crate_dir + "/", package["name"]))
                          # Each changed file belongs to the package with the deepest matching directory.
                          for path in changed:
                              owners = [entry for entry in packages if path.startswith(entry[0])]
                              if owners:
                                  touched.add(max(owners, key=lambda entry: len(entry[0]))[1])
                      else:
                          notes.append("`cargo metadata` failed, so touched crates are not marked")
                      crates = sorted(score.get("crates", []), key=lambda crate: crate.get("score", 100))
                      shown = [crate for crate in crates if crate.get("name") in touched] or crates[:5]
                      out += [
                          "",
                          f"### Crate health (workspace score {score.get('workspace_score')}/100, "
                          "higher is healthier)",
                          "",
                          "| Crate | Score | Severity | Top violation |",
                          "| --- | --- | --- | --- |",
                      ]
                      for crate in shown[:10]:
                          violations = crate.get("violations") or [{}]
                          top = violations[0].get("reason") or violations[0].get("metric") or ""
                          mark = " (touched)" if crate.get("name") in touched else ""
                          out.append(
                              f"| `{cell(crate.get('name'))}`{mark} | {crate.get('score')} "
                              f"| {cell(crate.get('severity'))} | {cell(top)} |"
                          )

          if notes:
              out += ["", "<details><summary>Notes</summary>", ""]
              out += [f"- {html.escape(note)}" for note in notes]
              out += ["", "</details>"]
          out += [
              "",
              "<sub>Structural analysis only: no SIRs, no model calls, no API keys. "
              "Advisory; it never blocks a merge.</sub>",
          ]
          with open("aether-review.md", "w") as report:
              report.write("\n".join(out) + "\n")
          print("\n".join(out))
          PY
          cat aether-review.md >> "$GITHUB_STEP_SUMMARY"

      # Pull requests from forks get a read-only token; they still have the job summary.
      - name: Post or update the review comment
        if: >-
          github.event_name == 'pull_request'
          && github.event.pull_request.head.repo.full_name == github.repository
        env:
          GH_TOKEN: ${{ github.token }}
          PR_NUMBER: ${{ github.event.pull_request.number }}
        run: |
          marker='<!-- aether-review -->'
          ids=$(gh api --paginate "repos/$GITHUB_REPOSITORY/issues/$PR_NUMBER/comments" \
            --jq ".[] | select(.user.login == \"github-actions[bot]\" and (.body | contains(\"$marker\"))) | .id")
          id=$(printf '%s\n' "$ids" | sed -n 1p)
          if [ -n "$id" ]; then
            gh api --method PATCH "repos/$GITHUB_REPOSITORY/issues/comments/$id" \
              -F body=@aether-review.md > /dev/null
          else
            gh pr comment "$PR_NUMBER" --body-file aether-review.md
          fi
"####
            .replacen("@SOURCE_SUFFIXES@", &suffixes, 1)
    }
}
